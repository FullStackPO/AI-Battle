import { START, END, StateSchema, StateGraph, type GraphNode } from "@langchain/langgraph";
import { HumanMessage } from "@langchain/core/messages"
import { createAgent, providerStrategy } from "langchain";
import * as z from "zod"
import { groqModel, cohereModel, googleModel } from "./model.service.js";

const State = new StateSchema({
    problem : z.string().default(""),
    solution_1 : z.string().default(""),
    solution_2 : z.string().default(""),
    judge : z.object({
        solution_1_score : z.number().default(0),
        solution_2_score : z.number().default(0),
        solution_1_feedback : z.string().default(""),
        solution_2_feedback : z.string().default("")
    }) 
})

const solutionNode:GraphNode<typeof State> = async(state) => {

    const[groq_solution, cohere_solution] = await Promise.all([
        groqModel.invoke(state.problem),
        cohereModel.invoke(state.problem)
    ])

    return {
        solution_1 : groq_solution.text,
        solution_2 : cohere_solution.text
    }

}

const judgeNode:GraphNode<typeof State> = async(state) => {

    const { problem, solution_1, solution_2 } = state

    const judge = createAgent({
        model : googleModel,
        tools : [],
        responseFormat : providerStrategy(z.object({
            solution_1_score : z.number().min(0).max(10),
            solution_2_score : z.number().min(0).max(10),
            solution_1_feedback : z.string(),
            solution_2_feedback : z.string()
        })),
        systemPrompt : `You are a judge tasked with evaluating two solutions generated by different AI models.
        Please provide a score out of 10 for each solution, along with your reasoning for the scores.`
    })

    const judgeResponse = await judge.invoke({
        messages : [
            new HumanMessage(
                `
                Problem : ${problem},
                Solution_1 : ${solution_1},
                Solution_2 : ${solution_2},
                Please evaluate the solution and provide the score and feedback
                `
            )
        ]
    })

    const { solution_1_score, solution_2_score, solution_1_feedback, solution_2_feedback } = judgeResponse.structuredResponse

    return {
        
        judge : {
            solution_1_score,
            solution_2_score,
            solution_1_feedback,
            solution_2_feedback
        }

    }

} 

const graph = new StateGraph(State)
        .addNode("solution", solutionNode)
        .addNode("judge", judgeNode)
        .addEdge(START, "solution")
        .addEdge("solution", "judge")
        .addEdge("judge", END)
        .compile()


export default async function (problem : string){
    const result = await graph.invoke({
        problem : problem
    })
    console.log(result)
    return result
}